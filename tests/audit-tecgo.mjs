import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const html=fs.readFileSync(new URL("../index.html",import.meta.url),"utf8");
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(Boolean);
assert(scripts.length>0,"No se hallaron scripts embebidos en TecGo");
for(const source of scripts)new vm.Script(source,{filename:"tecgo-inline.js"});
const source=scripts.join("\n");
assert(source.includes('summary.replaceChildren()'),"Resumen sin DOM seguro");
assert(source.includes('title.textContent'),"Historial sin textContent");
assert(source.includes('document.createTextNode(String(value||"Sin especificar"))'),"Historial puede interpolar datos sin escapar");
assert(!source.includes('$("#summary").innerHTML'),"Volvió el sumidero vulnerable de resumen");
assert(!source.includes('$("#orders-list").innerHTML = lista.map'),"Volvió el sumidero vulnerable en historial");
assert(!source.includes("Solicitud N° "+String.fromCharCode(36)+"{d.numero} enviada."),"La app afirma un envío WhatsApp no acreditado");
assert(source.includes('WhatsApp abierto. Confirma el envío'),"Falta aviso de estado no comprobado");
const i=source.indexOf('function renderOrders(){'),j=source.indexOf('function reenviar(i)',i);
assert(i>=0&&j>i,"No se encuentra historial");
assert(!source.slice(i,j).includes('innerHTML'),"El historial usa HTML dinámico");
console.log("TecGo: JavaScript válido; resumen e historial usan DOM seguro; envío de WhatsApp no inventado.");
